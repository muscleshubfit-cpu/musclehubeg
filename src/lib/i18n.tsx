const dicts: Record<Lang, Dict> = { en, ar };

type I18nCtx = {
 lang: Lang;
 setLang: (l: Lang) => void;
 t: (key: string) => string;
 dir: "rtl" | "ltr";
};

const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
 const [lang, setLangState] = useState<Lang>("ar");

 useEffect(() => {
 const saved = typeof window !== "undefined" ? (localStorage.getItem("mhe:lang") as Lang | null) : null;
 if (saved === "ar" || saved === "en") setLangState(saved);
 }, []);

 useEffect(() => {
 const dir = lang === "ar" ? "rtl" : "ltr";
 document.documentElement.lang = lang;
 document.documentElement.dir = dir;
 }, [lang]);

 const setLang = useCallback((l: Lang) => {
 setLangState(l);
 try {
 localStorage.setItem("mhe:lang", l);
 } catch {}
 }, []);

 const t = useCallback(
 (key: string) => dicts[lang][key] ?? dicts.en[key] ?? key,
 [lang],
 );

 return (
 <Ctx.Provider value={{ lang, setLang, t, dir: lang === "ar" ? "rtl" : "ltr" }}>
 {children}
 </Ctx.Provider>
 );
}

export function useI18n() {
 const ctx = useContext(Ctx);
 if (!ctx) throw new Error("useI18n must be used within I18nProvider");
 return ctx;
}
